"""Independent reference fixtures for the A minor pentatonic five-position system.

These are hand-checked against trusted per-string reference diagrams, NOT
generated by theory.py. The validation harness compares computed output to
these fixtures so an error in the theory engine cannot validate itself.

Reference: https://musedrill.com/eng-pentatonic-scale (per-string coordinates
for all five A minor pentatonic boxes; verified 2026-10-13, 60/60 notes match).

Convention: string 1 = high E, string 6 = low E (conventional numbering).
Each position is the standard "box" pattern taught in the conventional
5-position system for minor pentatonic.
"""
from __future__ import annotations

# Root locations for the A pitch class, used to mark is_root=True.
# On each string the A locations are fixed: string1 fret5/17, string2 fret10,
# string3 fret2/14, string4 fret7/19, string5 fret0/12, string6 fret5/17.
A_ROOT_LOCATIONS = {
    1: [5, 17],
    2: [10],
    3: [2, 14],
    4: [7, 19],
    5: [0, 12],
    6: [5, 17],
}

# Standard 5-position boxes for A minor pentatonic, expressed as
# per-string fret lists within each position's fret window.
# Verified against https://musedrill.com/eng-pentatonic-scale (2026-10-13, 60/60 notes match).
POSITIONS = [
    # Position 1: frets 5-8
    {"name": "Position 1", "fret_range": [5, 8],
     "strings": {
         6: [5, 8], 5: [5, 7], 4: [5, 7], 3: [5, 7], 2: [5, 8], 1: [5, 8]}},
    # Position 2: frets 7-10
    {"name": "Position 2", "fret_range": [7, 10],
     "strings": {
         6: [8, 10], 5: [7, 10], 4: [7, 10], 3: [7, 9], 2: [8, 10], 1: [8, 10]}},
    # Position 3: frets 9-13
    {"name": "Position 3", "fret_range": [9, 13],
     "strings": {
         6: [10, 12], 5: [10, 12], 4: [10, 12], 3: [9, 12], 2: [10, 13], 1: [10, 12]}},
    # Position 4: frets 12-15
    {"name": "Position 4", "fret_range": [12, 15],
     "strings": {
         6: [12, 15], 5: [12, 15], 4: [12, 14], 3: [12, 14], 2: [13, 15], 1: [12, 15]}},
    # Position 5: frets 14-17
    {"name": "Position 5", "fret_range": [14, 17],
     "strings": {
         6: [15, 17], 5: [15, 17], 4: [14, 17], 3: [14, 17], 2: [15, 17], 1: [15, 17]}},
]


def fixture_notes() -> list[dict]:
    """Yield all (string, fret, pitch_class, is_root) for the 5 positions."""
    from theory import CHROMATIC, note_at
    out = []
    for pos in POSITIONS:
        for s, frets in pos["strings"].items():
            for f in frets:
                pc = note_at(s, f)
                is_root = f in A_ROOT_LOCATIONS.get(s, []) and pc == "A"
                out.append({"string": s, "fret": f, "pitch_class": pc, "is_root": is_root, "position": pos["name"]})
    return out
